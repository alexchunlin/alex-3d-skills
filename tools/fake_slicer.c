/* Stand-in slicer for tools/test_cad_slice.sh. Args: --supports|--no-supports --out DIR file.stl
   Named *crashy*: segfaults (a slicer that crashes on its smoke test). Otherwise writes DIR/out.gcode with a
   PrusaSlicer-style header and support extrusions on a --supports pass, and reports on stderr what the sandbox allowed:
   a write to the path and a TCP connect to the 127.0.0.1 port named in fake.cfg next to the binary. */
#include <arpa/inet.h>
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/socket.h>
#include <unistd.h>
int main(int argc, char **argv) {
  if (strstr(argv[0], "crashy")) { volatile int *p = 0; *p = 1; }
  const char *out = ".";
  int sup = 0;
  for (int i = 1; i < argc; i++) {
    if (!strcmp(argv[i], "--supports")) sup = 1;
    if (!strcmp(argv[i], "--out") && i + 1 < argc) out = argv[++i];
  }
  char cfg[4096], outside[4096] = "", *slash;
  int port = 0;
  snprintf(cfg, sizeof cfg, "%s", argv[0]);
  if ((slash = strrchr(cfg, '/'))) strcpy(slash + 1, "fake.cfg");
  FILE *c = fopen(cfg, "r");
  if (c) { if (fscanf(c, "%4095s %d", outside, &port) < 2) port = 0; fclose(c); }
  const char *wr = "unset", *net = "unset";
  if (outside[0]) { FILE *o = fopen(outside, "w"); wr = o ? "allowed" : (errno == EPERM ? "denied" : "error"); if (o) fclose(o); }
  if (port) {
    int s = socket(AF_INET, SOCK_STREAM, 0); struct sockaddr_in a; memset(&a, 0, sizeof a);
    a.sin_family = AF_INET; a.sin_port = htons(port); a.sin_addr.s_addr = htonl(0x7f000001);
    net = s < 0 ? (errno == EPERM ? "denied" : "error") : connect(s, (struct sockaddr *)&a, sizeof a) == 0 ? "allowed" : (errno == EPERM ? "denied" : "refused");
  }
  char path[4096]; snprintf(path, sizeof path, "%s/out.gcode", out);
  FILE *f = fopen(path, "w"); if (!f) return 3;
  fprintf(f, "; generated by fake_slicer\n");
  for (int l = 1; l <= 10; l++) { fprintf(f, ";Z:%.1f\n;TYPE:External perimeter\nG1 X1 Y1 E1\n", 0.2 * l); if (sup && l >= 3 && l <= 5) fprintf(f, ";TYPE:Support material\nG1 X2 Y2 E0.1\n"); }
  fprintf(f, "; filament used [mm] = 1234.5\n; filament used [g] = 3.7\n; estimated printing time (normal mode) = 12m 30s\n");
  fclose(f);
  fprintf(stderr, "[warning] fake: object has a floating part\n[warning] probe write_outside=%s net=%s home=%s\n", wr, net, getenv("HOME") ? getenv("HOME") : "");
  return 0;
}
